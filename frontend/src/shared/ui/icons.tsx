/**
 * App-wide icon set — Phosphor icons, server-safe and bold by default.
 *
 * Every icon comes from Phosphor's SSR entry (`.../dist/ssr/*`), which renders
 * through a stateless base that reads no React context. That is what makes them
 * safe to import from Server Components: the package's default entry builds an
 * `IconContext` via `createContext` with no "use client" directive, so it
 * crashes the moment a Server Component evaluates it under the `react-server`
 * condition. The deep `dist/ssr/*` paths also keep tree-shaking per-icon — only
 * the icons a route actually imports ship in its bundle.
 *
 * Because SSR icons ignore `IconContext`, the app's default `bold` weight
 * (thicker strokes that stay crisp at the 14-16px sizes the UI draws at, where
 * lucide's thin strokes anti-aliased into a soft, "pixelated" look) is bound
 * here per icon rather than through a provider — a provider's context could
 * never reach server-rendered icons in the first place. A caller's own `weight`
 * still wins: it spreads in after the bound default.
 *
 * Generated by scripts (see the icon migration) — prefer regenerating over
 * hand-editing. Import icons from "@/shared/ui/icons".
 */
