/** Bind `weight="bold"` as this icon's default; a caller's own `weight` wins. */
function bold(Base: Icon): Icon {
  const Bold = forwardRef<SVGSVGElement, IconProps>((props, ref) =>
    createElement(Base, { ref, weight: "bold", ...props }),
  );
  Bold.displayName = Base.displayName;
  return Bold;
}

